import { mkdtemp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { spawnSync } from "node:child_process";
import path from "node:path";
import { compile } from "json-schema-to-typescript";
import Ajv2020 from "ajv/dist/2020.js";
import standalone from "ajv/dist/standalone/index.js";
import { build } from "esbuild";
import { format } from "prettier";
import ts from "typescript";
import { bundleContract, pascal, readContract, root } from "./contract.mjs";

const check = process.argv.includes("--check");
const contract = await readContract();
const bundled = bundleContract(contract);
const temporary = await mkdtemp(path.join(tmpdir(), "tasklease-codegen-"));
const outputs = new Map();
const banner = "// Generated by scripts/codegen.mjs. Do not edit.\n";

// TypeScript's empty interface means any non-nullish value, whereas a closed
// empty JSON object accepts only {}. Correct only schema-proven empty objects;
// open objects and interfaces with inherited requirements keep their meaning.
function closeEmptyObjectTypes(source, definitions) {
  const closedEmptyNames = new Set(
    Object.entries(definitions)
      .filter(
        ([, schema]) =>
          schema.type === "object" &&
          schema.additionalProperties === false &&
          Object.keys(schema.properties ?? {}).length === 0,
      )
      .map(([name]) => name),
  );
  const file = ts.createSourceFile(
    "protocol.ts",
    source,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS,
  );
  const entityName = (expression) => {
    if (ts.isIdentifier(expression)) return expression;
    if (ts.isPropertyAccessExpression(expression)) {
      return ts.factory.createQualifiedName(
        entityName(expression.expression),
        expression.name,
      );
    }
    throw new Error("Unexpected interface heritage in generated types");
  };
  const result = ts.transform(file, [
    (context) => (node) => {
      const visit = (child) => {
        if (
          ts.isInterfaceDeclaration(child) &&
          child.members.length === 0 &&
          closedEmptyNames.has(child.name.text)
        ) {
          const inherited = (child.heritageClauses ?? []).flatMap((clause) =>
            clause.types.map((type) =>
              ts.factory.createTypeReferenceNode(
                entityName(type.expression),
                type.typeArguments,
              ),
            ),
          );
          const closed = ts.factory.createTypeReferenceNode("Record", [
            ts.factory.createKeywordTypeNode(ts.SyntaxKind.StringKeyword),
            ts.factory.createKeywordTypeNode(ts.SyntaxKind.NeverKeyword),
          ]);
          return ts.factory.createTypeAliasDeclaration(
            child.modifiers,
            child.name,
            child.typeParameters,
            inherited.length
              ? ts.factory.createIntersectionTypeNode([...inherited, closed])
              : closed,
          );
        }
        return ts.visitEachChild(child, visit, context);
      };
      return ts.visitNode(node, visit);
    },
  ]);
  try {
    return ts.createPrinter().printFile(result.transformed[0]);
  } finally {
    result.dispose();
  }
}

try {
  const types = await compile(bundled, "ProtocolTypes", {
    bannerComment: banner.trim(),
    additionalProperties: false,
    unknownAny: true,
    style: { singleQuote: false },
  });
  outputs.set(
    "service/src/generated/protocol.ts",
    closeEmptyObjectTypes(types, bundled.$defs),
  );

  const ajv = new Ajv2020({
    schemas: [contract.common, ...Object.values(contract.operations)],
    allErrors: true,
    strict: true,
    code: { source: true, esm: true },
  });
  const exports = {};
  const names = [];
  for (const [operation, schema] of Object.entries(contract.operations)) {
    for (const kind of ["Request", "Response"]) {
      const name = pascal(operation) + kind;
      exports[`validate${name}`] = `${schema.$id}#/$defs/${kind}`;
      names.push(name);
    }
  }
  exports.validateErrorResponse = `${contract.common.$id}#/$defs/ErrorResponse`;
  names.push("ErrorResponse");
  const standaloneCode = standalone(ajv, exports);
  const validators = await build({
    stdin: { contents: standaloneCode, resolveDir: root, loader: "js" },
    bundle: true,
    write: false,
    format: "esm",
    platform: "neutral",
    legalComments: "none",
  });
  outputs.set(
    "service/src/generated/validators.js",
    banner + validators.outputFiles[0].text,
  );
  outputs.set(
    "service/src/generated/validators.d.ts",
    banner +
      'import type { ValidateFunction } from "ajv";\n' +
      `import type { ${names.join(", ")} } from "./protocol.js";\n` +
      names
        .map(
          (name) => `export const validate${name}: ValidateFunction<${name}>;`,
        )
        .join("\n") +
      "\n",
  );
  const operationNames = Object.keys(contract.operations).filter(
    (operation) => operation !== "version",
  );
  outputs.set(
    "service/src/generated/requests.ts",
    banner +
      'import * as validators from "./validators.js";\n' +
      'import type { OperationRequests } from "./protocol.js";\n' +
      'import type { ValidateFunction } from "ajv";\n' +
      "export type Operation = keyof OperationRequests;\n" +
      "export const requestValidators: { [K in Operation]: ValidateFunction<OperationRequests[K]> } = {\n" +
      operationNames
        .map(
          (operation) =>
            `${JSON.stringify(operation)}: validators.validate${pascal(operation)}Request,`,
        )
        .join("\n") +
      "\n};\n",
  );

  const input = path.join(temporary, "protocol.json");
  const output = path.join(temporary, "protocol.py");
  await writeFile(input, JSON.stringify(bundled));
  const result = spawnSync(
    "uv",
    [
      "run",
      "--project",
      path.join(root, "python"),
      "--frozen",
      "datamodel-codegen",
      "--input",
      input,
      "--input-file-type",
      "jsonschema",
      "--output",
      output,
      "--output-model-type",
      "typing.TypedDict",
      "--target-python-version",
      "3.12",
      "--disable-timestamp",
      "--use-standard-collections",
      "--use-union-operator",
      "--use-title-as-name",
      "--no-use-closed-typed-dict",
      "--custom-file-header",
      "# Generated by scripts/codegen.mjs. Do not edit.",
      "--formatters",
      "ruff-format",
    ],
    {
      cwd: root,
      env: process.env,
      encoding: "utf8",
    },
  );
  if (result.status !== 0) {
    throw new Error(
      result.error?.message ?? result.stderr ?? "Python codegen failed",
    );
  }
  outputs.set(
    "python/src/tasklease/generated/protocol.py",
    await readFile(output, "utf8"),
  );
  outputs.set(
    "python/src/tasklease/generated/__init__.py",
    '"""Generated protocol types. Regenerate with make codegen."""\n',
  );

  const drift = [];
  for (const [relative, unformatted] of outputs) {
    const contents = relative.endsWith(".py")
      ? unformatted
      : await format(unformatted, {
          parser: relative.endsWith(".ts") ? "typescript" : "babel",
        });
    const destination = path.join(root, relative);
    if (check) {
      const existing = await readFile(destination, "utf8").catch((error) => {
        if (error.code === "ENOENT") return null;
        throw error;
      });
      if (existing !== contents) drift.push(relative);
    } else {
      await mkdir(path.dirname(destination), { recursive: true });
      await writeFile(destination, contents);
    }
  }
  if (drift.length) {
    throw new Error(
      `Generated files have drifted:\n${drift.join("\n")}\nRun make codegen.`,
    );
  }
  // Compiling a declaration file alone does not prove its public types are
  // usable. Exercise real request/data assignments and validator narrowing.
  for (const [command, args] of [
    [
      process.execPath,
      [
        path.join(root, "node_modules/typescript/bin/tsc"),
        "--noEmit",
        "--strict",
        "--skipLibCheck",
        "--module",
        "esnext",
        "--moduleResolution",
        "bundler",
        path.join(root, "scripts/typecheck_contract.ts"),
      ],
    ],
    [
      "uv",
      [
        "run",
        "--project",
        path.join(root, "python"),
        "--frozen",
        "mypy",
        "--config-file",
        path.join(root, "python/pyproject.toml"),
        path.join(root, "scripts/typecheck_contract.py"),
      ],
    ],
  ]) {
    const result = spawnSync(command, args, {
      cwd: root,
      encoding: "utf8",
      env: process.env,
    });
    if (result.status !== 0) {
      throw new Error(
        result.error?.message ?? `${result.stdout}\n${result.stderr}`,
      );
    }
  }
  console.log(
    `${check ? "Checked" : "Generated"} ${outputs.size} protocol artifacts.`,
  );
} finally {
  await rm(temporary, { recursive: true, force: true });
}
